#[cfg(any(debug_assertions, test))]
pub fn exporter() -> specta_typescript::Typescript {
    specta_typescript::Typescript::default()
        .header("// @ts-nocheck\n// Generated by tauri-specta. Do not edit; run `pnpm bindings`.\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Regenerate with `UPDATE_BINDINGS=1 cargo test -p freelance-crm bindings`.
    #[test]
    fn bindings_are_up_to_date() {
        let dir = tempfile::tempdir().unwrap();
        let fresh_path = dir.path().join("bindings.ts");
        builder::<tauri::Wry>()
            .export(exporter(), &fresh_path)
            .unwrap();
        let fresh = std::fs::read_to_string(&fresh_path).unwrap();

        if std::env::var_os("UPDATE_BINDINGS").is_some() {
            std::fs::write(BINDINGS_PATH, &fresh).unwrap();
            return;
        }
        let committed = std::fs::read_to_string(BINDINGS_PATH).unwrap_or_default();
        assert!(
            committed == fresh,
            "src/lib/api/bindings.ts is stale; run `pnpm bindings`"
        );
    }
}
